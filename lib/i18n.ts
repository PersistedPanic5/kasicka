/**
 * Best-effort browser-language sniff for the public debt-share page, which
 * has no signed-in profile to read a preference from. Only ever returns
 * 'cs' or 'en' — anything else (a debtor's phone set to German, say) falls
 * back to English rather than guessing further.
 */
export function detectBrowserLanguage(): Language {
  if (typeof navigator === 'undefined') return 'en';
  const candidates = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  for (const raw of candidates) {
    if (raw && raw.toLowerCase().startsWith('cs')) return 'cs';
  }
  return 'en';
}
